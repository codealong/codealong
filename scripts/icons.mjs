// Generates every use of the mark from design/brand/mark.svg, then renders the app
// icon with headless Chrome and runs `tauri icon` for the native bundle sizes.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync, rmSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const mark = readFileSync(join(root, 'design/brand/mark.svg'), 'utf8');
const viewBox = mark.match(/viewBox="([^"]+)"/)[1];
const paths = [...mark.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((match) => match[1]);
if (paths.length !== 2) throw new Error('The master mark must contain the C and commit-node paths.');
const tokens = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8')).color.tokens;
const color = (name, theme) => tokens.find((token) => token.name === name).value[theme];
const states = {
  idle: { label: 'Idle', token: 'logo-idle' },
  working: { label: 'Working', token: 'logo-working' },
  unread: { label: 'Your turn', token: 'unread-solid' },
  needs: { label: 'Needs you', token: 'attn-solid' },
  error: { label: 'Session error', token: 'alert-solid' },
};
const shapes = (node) => `<path d="${paths[0]}"/><path fill="${node}" d="${paths[1]}"/>`;

writeFileSync(join(root, 'src/ui/brand.ts'), `// Generated by npm run icons from design/brand/mark.svg.\nexport const MARK_VIEW_BOX = ${JSON.stringify(viewBox)};\nexport const MARK_PATHS = ${JSON.stringify(paths, null, 2)};\n`);

// A flat dark tile gives the Dock icon the same silhouette in either macOS theme. Codealong Dev,
// what scripts/relaunch.sh builds, has a light one, so a build of the repo never passes for the
// app you installed in the Dock or ⌘-Tab; its edge keeps it apart from a light Dock.
const tiles = {
  release: { name: 'Codealong', tile: color('surface', 'dark'), edge: '', theme: 'dark' },
  dev: { name: 'Codealong Dev', tile: color('surface', 'light'), edge: ` stroke="${color('line', 'light')}" stroke-width="12"`, theme: 'light' },
};
const appIcon = (status, variant = 'release') => {
  const t = tiles[variant];
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><title>${t.name} · ${states[status].label}</title><rect x="100" y="100" width="824" height="824" rx="185" fill="${t.tile}"${t.edge}/><svg x="202" y="202" width="620" height="620" viewBox="${viewBox}" fill="${color('ink', t.theme)}">${shapes(color(states[status].token, t.theme))}</svg></svg>\n`;
};
const svg = appIcon('idle');
writeFileSync(join(root, 'design/app-icon.svg'), svg);
mkdirSync(join(root, 'public/logos'), { recursive: true });
for (const [status, { label, token }] of Object.entries(states)) {
  const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"><title>Codealong · ${label}</title><style>:root{color:${color('ink', 'light')};--node:${color(token, 'light')}}@media(prefers-color-scheme:dark){:root{color:${color('ink', 'dark')};--node:${color(token, 'dark')}}}</style><g fill="currentColor">${shapes('var(--node)')}</g></svg>\n`;
  writeFileSync(join(root, `public/logos/${status}.svg`), favicon);
  if (status === 'idle') writeFileSync(join(root, 'public/favicon.svg'), favicon);
}

// A compact reference sheet, generated from the same geometry and colors as the app.
const heading = { light: 'Light', dark: 'Dark', dock: 'Dock', 'dock-dev': 'Dock · Codealong Dev' };
const sheet = ['light', 'dark', 'dock', 'dock-dev'].map((theme) => `<section class="${theme}"><h2>${heading[theme]}</h2><div class="row">${Object.entries(states).map(([status, { label, token }]) => `<figure>${theme === 'dock' ? appIcon(status) : theme === 'dock-dev' ? appIcon(status, 'dev') : `<svg viewBox="${viewBox}" fill="${color('ink', theme)}">${shapes(color(token, theme))}</svg>`}<figcaption>${label}</figcaption></figure>`).join('')}</div></section>`).join('');
writeFileSync(join(root, 'design/brand/preview.html'), `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Codealong · Status marks</title><style>body{margin:0;background:${color('ground', 'light')};color:${color('ink', 'light')};font:14px system-ui}header{padding:28px 40px}h1{margin:0 0 8px;font-size:24px}p{margin:0;color:${color('ink-2', 'light')}}section{padding:20px 40px}h2{font-size:12px;text-transform:uppercase;letter-spacing:.12em;margin:0 0 8px}.row{display:grid;grid-template-columns:repeat(5,1fr);gap:24px;max-width:1000px;margin:auto}figure{margin:0;text-align:center}svg{display:block;width:110px;height:110px;max-width:100%;margin:0 auto 12px}.light{background:${color('surface', 'light')}}.dark{background:${color('surface', 'dark')};color:${color('ink', 'dark')}}.dock svg,.dock-dev svg{width:138px;height:138px;margin-bottom:0}@media(max-width:600px){header,section{padding:20px}.row{gap:8px}figcaption{font-size:11px}}</style><header><h1>Codealong · Status marks</h1><p>The chosen C stays neutral. Its commit node shows what needs your attention.</p></header>${sheet}</html>\n`);

const dir = mkdtempSync(join(tmpdir(), 'codealong-icon-'));
const html = join(dir, 'icon.html');
function render(svg, png) {
  writeFileSync(html, `<!doctype html><html><body style="margin:0;background:transparent">${svg.replace('<svg ', '<svg style="display:block;width:1024px;height:1024px" ')}</body></html>`);
  // Its profile goes with `dir`: given none, headless Chrome leaves one in Application Support.
  execFileSync('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', [
    '--headless=new', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1', `--user-data-dir=${join(dir, 'profile')}`,
    '--default-background-color=00000000', '--window-size=1024,1024', `--screenshot=${png}`, `file://${html}`,
  ], { stdio: 'ignore' });
}
const png = join(root, 'src-tauri/app-icon.png');
const devPng = join(root, 'src-tauri/app-icon-dev.png');
try {
  render(svg, png);
  render(appIcon('idle', 'dev'), devPng);
  mkdirSync(join(root, 'src-tauri/icons/status'), { recursive: true });
  mkdirSync(join(root, 'src-tauri/icons/dev/status'), { recursive: true });
  for (const status of Object.keys(states).filter((s) => s !== 'idle')) {
    render(appIcon(status), join(root, `src-tauri/icons/status/${status}.png`));
    render(appIcon(status, 'dev'), join(root, `src-tauri/icons/dev/status/${status}.png`));
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
execFileSync('npx', ['tauri', 'icon', png], { cwd: root, stdio: 'inherit' });
// Codealong Dev's bundle icons (src-tauri/tauri.dev.conf.json names them).
execFileSync('npx', ['tauri', 'icon', devPng, '-o', 'src-tauri/icons/dev'], { cwd: root, stdio: 'inherit' });

// Keep only what the macOS (and a future Windows) bundle uses.
for (const icons of [join(root, 'src-tauri/icons'), join(root, 'src-tauri/icons/dev')]) {
  for (const name of readdirSync(icons)) {
    if (name === 'android' || name === 'ios' || name.startsWith('Square') || name === 'StoreLogo.png') {
      rmSync(join(icons, name), { recursive: true, force: true });
    }
  }
}
