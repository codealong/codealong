// Generates every use of the mark from design/brand/mark.svg, then renders the app
// icon with headless Chrome and runs `tauri icon` for the native bundle sizes. With
// --menu-bar it renders only the menu bar item's mark.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync, rmSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const mark = readFileSync(join(root, 'design/brand/mark.svg'), 'utf8');
const viewBox = mark.match(/viewBox="([^"]+)"/)[1];
const paths = [...mark.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((match) => match[1]);
if (paths.length !== 2) throw new Error('The master mark must contain the C and commit-node paths.');
const tokens = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8')).color.tokens;
const color = (name, theme) => tokens.find((token) => token.name === name).value[theme];
const states = {
  idle: { label: 'Idle', token: 'logo-idle' },
  working: { label: 'Working', token: 'logo-working' },
  unread: { label: 'Your turn', token: 'unread-solid' },
  needs: { label: 'Needs you', token: 'attn-solid' },
  error: { label: 'Session error', token: 'alert-solid' },
};
const shapes = (node) => `<path d="${paths[0]}"/><path fill="${node}" d="${paths[1]}"/>`;

writeFileSync(join(root, 'src/ui/brand.ts'), `// Generated by npm run icons from design/brand/mark.svg.\nexport const MARK_VIEW_BOX = ${JSON.stringify(viewBox)};\nexport const MARK_PATHS = ${JSON.stringify(paths, null, 2)};\n`);

// Dark smoked-glass tile for Codealong and frosted light glass for Codealong Dev (what
// scripts/relaunch.sh builds), so a build of the repo never passes for the installed app in the
// Dock or ⌘-Tab. Both use subtle top-down lighting, a hairline refractive rim, and gentle depth on
// the C and commit node so the static bundle icon and all five live Dock states (logo.rs) sit
// naturally among macOS Liquid Glass icons.
const tiles = {
  release: {
    name: 'Codealong',
    theme: 'dark',
    bgTop: '#262b2f',
    bgMid: '#181b1e',
    bgBot: '#101214',
    topLight: 'rgba(255,255,255,0.12)',
    outerStroke: 'rgba(255,255,255,0.10)',
    outerWidth: 3,
    rimTop: 'rgba(255,255,255,0.34)',
    rimMid: 'rgba(255,255,255,0.06)',
    rimBot: 'rgba(255,255,255,0.16)',
    cTop: '#f5f7f4',
    cBot: '#d9ddd8',
    cShadow: 'rgba(0,0,0,0.45)',
    cShadowDy: 14,
    cShadowBlur: 18,
    nodeShadow: 'rgba(0,0,0,0.38)',
    auraOpacity: 0.22,
    nodeSheenTop: 'rgba(255,255,255,0.34)',
    nodeShadeBot: 'rgba(0,0,0,0.18)',
  },
  dev: {
    name: 'Codealong Dev',
    theme: 'light',
    bgTop: '#ffffff',
    bgMid: '#f6f8f6',
    bgBot: '#e8ece9',
    topLight: 'rgba(255,255,255,0.85)',
    outerStroke: 'rgba(20,24,23,0.15)',
    outerWidth: 6,
    rimTop: 'rgba(255,255,255,0.95)',
    rimMid: 'rgba(255,255,255,0.32)',
    rimBot: 'rgba(255,255,255,0.78)',
    cTop: '#262c2b',
    cBot: '#111514',
    cShadow: 'rgba(20,24,23,0.20)',
    cShadowDy: 10,
    cShadowBlur: 14,
    nodeShadow: 'rgba(20,24,23,0.22)',
    auraOpacity: 0.14,
    nodeSheenTop: 'rgba(255,255,255,0.38)',
    nodeShadeBot: 'rgba(0,0,0,0.12)',
  },
};
const appIcon = (status, variant = 'release') => {
  const t = tiles[variant];
  const id = `${variant}-${status}`;
  const nodeColor = color(states[status].token, t.theme);
  const aura = status === 'idle'
    ? ''
    : `<circle cx="536" cy="512" r="245" fill="url(#aura-${id})"/>`;
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">`,
    `<title>${t.name} · ${states[status].label}</title>`,
    `<defs>`,
    `<clipPath id="clip-${id}"><rect x="100" y="100" width="824" height="824" rx="185"/></clipPath>`,
    `<linearGradient id="bg-${id}" x1="512" y1="100" x2="512" y2="924" gradientUnits="userSpaceOnUse">`,
    `<stop offset="0%" stop-color="${t.bgTop}"/>`,
    `<stop offset="52%" stop-color="${t.bgMid}"/>`,
    `<stop offset="100%" stop-color="${t.bgBot}"/>`,
    `</linearGradient>`,
    `<radialGradient id="spec-${id}" cx="512" cy="140" r="560" gradientUnits="userSpaceOnUse">`,
    `<stop offset="0%" stop-color="${t.topLight}"/>`,
    `<stop offset="65%" stop-color="rgba(255,255,255,0)"/>`,
    `</radialGradient>`,
    `<linearGradient id="rim-${id}" x1="220" y1="100" x2="804" y2="924" gradientUnits="userSpaceOnUse">`,
    `<stop offset="0%" stop-color="${t.rimTop}"/>`,
    `<stop offset="48%" stop-color="${t.rimMid}"/>`,
    `<stop offset="100%" stop-color="${t.rimBot}"/>`,
    `</linearGradient>`,
    status === 'idle' ? '' : `<radialGradient id="aura-${id}" cx="536" cy="512" r="245" gradientUnits="userSpaceOnUse"><stop offset="0%" stop-color="${nodeColor}" stop-opacity="${t.auraOpacity}"/><stop offset="100%" stop-color="${nodeColor}" stop-opacity="0"/></radialGradient>`,
    `<linearGradient id="cfill-${id}" x1="534" y1="61" x2="534" y2="1009" gradientUnits="userSpaceOnUse">`,
    `<stop offset="0%" stop-color="${t.cTop}"/>`,
    `<stop offset="100%" stop-color="${t.cBot}"/>`,
    `</linearGradient>`,
    `<linearGradient id="nsheen-${id}" x1="600" y1="399" x2="600" y2="671" gradientUnits="userSpaceOnUse">`,
    `<stop offset="0%" stop-color="${t.nodeSheenTop}"/>`,
    `<stop offset="48%" stop-color="rgba(255,255,255,0)"/>`,
    `<stop offset="100%" stop-color="${t.nodeShadeBot}"/>`,
    `</linearGradient>`,
    `<filter id="cshadow-${id}" x="-15%" y="-15%" width="130%" height="140%">`,
    `<feDropShadow dx="0" dy="${t.cShadowDy}" stdDeviation="${t.cShadowBlur}" flood-color="${t.cShadow}"/>`,
    `</filter>`,
    `<filter id="nshadow-${id}" x="-25%" y="-25%" width="150%" height="160%">`,
    `<feDropShadow dx="0" dy="10" stdDeviation="14" flood-color="${t.nodeShadow}"/>`,
    `</filter>`,
    `</defs>`,
    `<rect x="100" y="100" width="824" height="824" rx="185" fill="url(#bg-${id})"/>`,
    `<g clip-path="url(#clip-${id})">`,
    `<rect x="100" y="100" width="824" height="824" fill="url(#spec-${id})"/>`,
    aura,
    `</g>`,
    `<rect x="103" y="103" width="818" height="818" rx="182" fill="none" stroke="url(#rim-${id})" stroke-width="6"/>`,
    `<rect x="100" y="100" width="824" height="824" rx="185" fill="none" stroke="${t.outerStroke}" stroke-width="${t.outerWidth}"/>`,
    `<svg x="202" y="202" width="620" height="620" viewBox="${viewBox}">`,
    `<path d="${paths[0]}" fill="url(#cfill-${id})" filter="url(#cshadow-${id})"/>`,
    `<g filter="url(#nshadow-${id})"><path d="${paths[1]}" fill="${nodeColor}"/><path d="${paths[1]}" fill="url(#nsheen-${id})"/></g>`,
    `</svg>`,
    `</svg>\n`,
  ].join('');
};
const svg = appIcon('idle');
writeFileSync(join(root, 'design/app-icon.svg'), svg);
mkdirSync(join(root, 'public/logos'), { recursive: true });
for (const [status, { label, token }] of Object.entries(states)) {
  const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"><title>Codealong · ${label}</title><style>:root{color:${color('ink', 'light')};--node:${color(token, 'light')}}@media(prefers-color-scheme:dark){:root{color:${color('ink', 'dark')};--node:${color(token, 'dark')}}}</style><g fill="currentColor">${shapes('var(--node)')}</g></svg>\n`;
  writeFileSync(join(root, `public/logos/${status}.svg`), favicon);
  if (status === 'idle') writeFileSync(join(root, 'public/favicon.svg'), favicon);
}

// A compact reference sheet, generated from the same geometry and colors as the app.
const heading = { light: 'Light', dark: 'Dark', dock: 'Dock', 'dock-dev': 'Dock · Codealong Dev' };
const sheet = ['light', 'dark', 'dock', 'dock-dev'].map((theme) => `<section class="${theme}"><h2>${heading[theme]}</h2><div class="row">${Object.entries(states).map(([status, { label, token }]) => `<figure>${theme === 'dock' ? appIcon(status) : theme === 'dock-dev' ? appIcon(status, 'dev') : `<svg viewBox="${viewBox}" fill="${color('ink', theme)}">${shapes(color(token, theme))}</svg>`}<figcaption>${label}</figcaption></figure>`).join('')}</div></section>`).join('');
writeFileSync(join(root, 'design/brand/preview.html'), `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Codealong · Status marks</title><style>body{margin:0;background:${color('ground', 'light')};color:${color('ink', 'light')};font:14px system-ui}header{padding:28px 40px}h1{margin:0 0 8px;font-size:24px}p{margin:0;color:${color('ink-2', 'light')}}section{padding:20px 40px}h2{font-size:12px;text-transform:uppercase;letter-spacing:.12em;margin:0 0 8px}.row{display:grid;grid-template-columns:repeat(5,1fr);gap:24px;max-width:1000px;margin:auto}figure{margin:0;text-align:center}svg{display:block;width:110px;height:110px;max-width:100%;margin:0 auto 12px}.light{background:${color('surface', 'light')}}.dark{background:${color('surface', 'dark')};color:${color('ink', 'dark')}}.dock svg,.dock-dev svg{width:138px;height:138px;margin-bottom:0}@media(max-width:600px){header,section{padding:20px}.row{gap:8px}figcaption{font-size:11px}}</style><header><h1>Codealong · Status marks</h1><p>The chosen C stays neutral. Its commit node shows what needs your attention.</p></header>${sheet}</html>\n`);

const dir = mkdtempSync(join(tmpdir(), 'codealong-icon-'));
const html = join(dir, 'icon.html');
function render(svg, png, size = 1024) {
  writeFileSync(html, `<!doctype html><html><body style="margin:0;background:transparent">${svg.replace('<svg ', `<svg style="display:block;width:${size}px;height:${size}px" `)}</body></html>`);
  // MacAppCodeSignClone is off for the reason scripts/preview.sh gives.
  execFileSync('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', [
    '--headless=new', '--disable-features=MacAppCodeSignClone', '--disable-gpu','--hide-scrollbars', '--force-device-scale-factor=1',
    '--default-background-color=00000000', `--window-size=${size},${size}`, `--screenshot=${png}`, `file://${html}`,
  ], { stdio: 'ignore' });
}

// The menu bar item's mark (src-tauri/src/menubar.rs): black on clear, which macOS takes as a
// template and draws in the menu bar's own color, 16 points tall at twice that with a point of
// room around it in the 18 the item gives it.
const menuBarIcon = `<svg xmlns="http://www.w3.org/2000/svg" width="36" height="36" viewBox="0 0 36 36"><svg x="2" y="2" width="32" height="32" viewBox="${viewBox}" fill="#000">${shapes('#000')}</svg></svg>\n`;
const menuBarPng = join(root, 'src-tauri/icons/menubar.png');
if (process.argv.includes('--menu-bar')) {
  try {
    render(menuBarIcon, menuBarPng, 36);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
  process.exit(0);
}
const png = join(root, 'src-tauri/app-icon.png');
const devPng = join(root, 'src-tauri/app-icon-dev.png');
try {
  render(svg, png);
  render(appIcon('idle', 'dev'), devPng);
  render(menuBarIcon, menuBarPng, 36);
  mkdirSync(join(root, 'src-tauri/icons/status'), { recursive: true });
  mkdirSync(join(root, 'src-tauri/icons/dev/status'), { recursive: true });
  for (const status of Object.keys(states).filter((s) => s !== 'idle')) {
    render(appIcon(status), join(root, `src-tauri/icons/status/${status}.png`));
    render(appIcon(status, 'dev'), join(root, `src-tauri/icons/dev/status/${status}.png`));
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
execFileSync('npx', ['tauri', 'icon', png], { cwd: root, stdio: 'inherit' });
// Codealong Dev's bundle icons (src-tauri/tauri.dev.conf.json names them).
execFileSync('npx', ['tauri', 'icon', devPng, '-o', 'src-tauri/icons/dev'], { cwd: root, stdio: 'inherit' });

// Keep only what the macOS (and a future Windows) bundle uses.
for (const icons of [join(root, 'src-tauri/icons'), join(root, 'src-tauri/icons/dev')]) {
  for (const name of readdirSync(icons)) {
    if (name === 'android' || name === 'ios' || name.startsWith('Square') || name === 'StoreLogo.png') {
      rmSync(join(icons, name), { recursive: true, force: true });
    }
  }
}
